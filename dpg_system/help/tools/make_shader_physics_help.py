# ----------------------------------------------------------------- mgl_shader
body = """Arbitrary GLSL in the scene chain, ShaderToy-compatible.

THE NODE:

mgl_shader   your own fragment shader, over the whole frame

TWO MODES, AND THEY ARE DIFFERENT JOBS:

generator      draws a full-screen quad with your shader. Nothing that came
               before is looked at - the shader makes the picture.
post_process   grabs what the chain has drawn SO FAR, hands it to the shader as
               iChannel0, and draws the result. This is where a filter goes.

Put a generator at the start of a chain and a post_process at the end. A
post_process with nothing before it has nothing to work on.

SHADERTOY CODE MOSTLY JUST WORKS:
If your source contains mainImage, the node wraps it with the ShaderToy uniforms
- iTime, iResolution, iFrame, iMouse, iChannel0 to 3, iTimeDelta - so a shader
copied from ShaderToy runs without editing.

If it does not contain mainImage, the source is used as written, with the uniform
declarations added if there is no #version line. So you can write plain GLSL and
still have the uniforms available.

That compatibility is the reason to reach for this node. There is an enormous
amount of published shader work that will run here directly.

FILE OR TEXT, AND auto_reload IS THE ONE TO USE:
'file' points at a .glsl on disk and 'auto_reload' watches it, so the picture
updates as you save from an editor. That loop - edit, save, look - is much
faster than pasting.

'shader_text' takes the source directly, which is fine for something short or
for a shader generated by the patch itself.

'status' reports compilation. A shader that fails to compile leaves the previous
one running rather than going black, so watch that outlet - a silent failure
looks exactly like a shader that did nothing.

THE UNIFORMS YOU DRIVE:
'iTime' and 'iMouse' are inlets, so they do not have to come from the clock and
the mouse. Feed iTime from a signal and the shader runs on your time rather than
the wall's - which is how you scrub, freeze, or run it from an audio envelope.

The extra channels take textures for the shader to sample.

SYNTAX:
mgl_shader

EXAMPLE:
mgl_shader

INPUTS and PARAMETERS:

mgl chain in:
The scene chain.

file / shader_text / reload / auto_reload:
Where the source comes from, and whether to watch it.

mode:
generator or post_process.

iTime / iMouse:
The standard uniforms, as inlets you can drive.

OUTPUTS: 

mgl chain out:
The chain, continued.

status:
Whether it compiled.

RELATED:
mgl_texture and the mgl pages for the rest of the scene chain.
mgl_smpl_mesh if what you want to draw is a body."""

