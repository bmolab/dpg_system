# -------------------------------------------------------------- pybullet_body
body = """A physically simulated body, standing in for a real one.

THE NODE:

pybullet_body   a humanoid in a physics simulation

It loads a humanoid model into a Bullet physics world with gravity, and steps it
forward when you tell it to. Each step, the body falls, collides with the ground
and responds to whatever forces are on it.

WHAT IT IS FOR HERE:
Not games. It is a way to ask what a body would do - to check whether a pose is
physically possible, to see what forces a movement implies, or to let something
respond to a push rather than to a recording.

Because it is a real simulation, the answers include the parts you did not
author: a body that overbalances, a limb that swings past where it was aimed, the
floor pushing back.

'step' ADVANCES IT, AND YOU DECIDE WHEN:
Nothing moves until you step it. That is deliberate - it lets the simulation run
in lockstep with the patch rather than on its own clock, so the physics and
whatever is driving it stay in agreement.

Step it once per frame for real-time behaviour. Step it several times per frame
and it runs fast; step it rarely and it runs slow, in its own time rather than
becoming jerky.

'pelvis_position' and 'pelvis_orientation' PLACE THE BODY:
The root of the figure is driven rather than simulated - you say where the pelvis
is and which way it faces, and the rest hangs off it and responds. That is what
lets a captured performance drive a simulated body: the pelvis follows the
recording, and the limbs do what physics says.

The joints have force-torque sensors enabled where the model allows it, so what
comes back includes what the joints were having to do.

'pose_out' and 'position_out' report the result - where everything ended up after
the step, which is not necessarily where you asked it to be.

SYNTAX:
pybullet_body

EXAMPLE:
pybullet_body

INPUTS and PARAMETERS:

step:
Advance the simulation. Nothing happens until you do.

pelvis_position / pelvis_orientation:
Where the root of the body is, and which way it faces.

OUTPUTS: 

pose_out:
The joint angles after the step.

position_out:
Where the body ended up.

RELATED:
smpl_torque, which computes what a movement implies without simulating it.
smpl_body and gl_body to draw the result."""

